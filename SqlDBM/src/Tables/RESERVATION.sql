-- ************************************** "RESERVATION"
CREATE MULTISET TABLE "RESERVATION" (
  "RESERVATION_ID" integer NOT NULL,
  "CUSTOMER_ID" integer NOT NULL,
  "VEHICLE_CLASS_ID" integer NOT NULL,
  "RATE_CODE_ID" integer NOT NULL,
  "PICKUP_LOCATION_ID" integer NOT NULL,
  "RETURN_LOCATION_ID" integer NOT NULL,
  "RESERVATION_DATE" timestamp(0) NULL DEFAULT CURRENT_TIMESTAMP(0),
  "REQUESTED_PICKUP_TS" timestamp(0) NOT NULL,
  "REQUESTED_RETURN_TS" timestamp(0) NOT NULL,
  "RESERVATION_STATUS" varchar(20) NULL DEFAULT 'CONFIRMED',
  CONSTRAINT "PK_RESERVATION" PRIMARY KEY ("RESERVATION_ID"),
  CONSTRAINT "FK_RES_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMER" ("CUSTOMER_ID"),
  CONSTRAINT "FK_RES_CLASS" FOREIGN KEY ("VEHICLE_CLASS_ID") REFERENCES "VEHICLE_CLASS" ("VEHICLE_CLASS_ID"),
  CONSTRAINT "FK_RES_RATECODE" FOREIGN KEY ("RATE_CODE_ID") REFERENCES "RATE_CODE" ("RATE_CODE_ID"),
  CONSTRAINT "FK_RES_PICKUP_LOC" FOREIGN KEY ("PICKUP_LOCATION_ID") REFERENCES "LOCATION" ("LOCATION_ID"),
  CONSTRAINT "FK_RES_RETURN_LOC" FOREIGN KEY ("RETURN_LOCATION_ID") REFERENCES "LOCATION" ("LOCATION_ID")
)
PRIMARY INDEX PI_RESERVATION (CUSTOMER_ID);