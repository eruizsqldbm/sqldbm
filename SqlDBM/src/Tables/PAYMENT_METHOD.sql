-- ************************************** "PAYMENT_METHOD"
CREATE MULTISET TABLE "PAYMENT_METHOD" (
  "PAYMENT_METHOD_ID" integer NOT NULL,
  "CUSTOMER_ID" integer NOT NULL,
  "METHOD_TYPE" varchar(20) NOT NULL,
  "CARD_BRAND" varchar(20) NULL,
  "CARD_LAST4" varchar(4) NULL,
  "CARD_EXPIRATION" date NULL,
  "IS_DEFAULT" char(1) NULL DEFAULT 'N',
  CONSTRAINT "PK_PAYMENT_METHOD" PRIMARY KEY ("PAYMENT_METHOD_ID"),
  CONSTRAINT "FK_PAYMETHOD_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMER" ("CUSTOMER_ID")
)
PRIMARY INDEX PI_PAYMENT_METHOD (CUSTOMER_ID);