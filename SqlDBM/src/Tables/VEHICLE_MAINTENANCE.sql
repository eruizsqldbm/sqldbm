-- ************************************** "VEHICLE_MAINTENANCE"
CREATE MULTISET TABLE "VEHICLE_MAINTENANCE" (
  "MAINTENANCE_ID" integer NOT NULL,
  "VEHICLE_ID" integer NOT NULL,
  "SERVICE_TYPE" varchar(50) NOT NULL,
  "SERVICE_DATE" date NOT NULL,
  "ODOMETER_AT_SERVICE" integer NULL,
  "SERVICE_COST" decimal(10,2) NULL,
  "NOTES" varchar(500) NULL,
  "AGREEMENT_LINE_ID" integer NOT NULL,
  CONSTRAINT "PK_VEHICLE_MAINTENANCE" PRIMARY KEY ("MAINTENANCE_ID"),
  CONSTRAINT "FK_MAINT_VEHICLE" FOREIGN KEY ("VEHICLE_ID") REFERENCES "VEHICLE" ("VEHICLE_ID"),
  CONSTRAINT "FK_2" FOREIGN KEY ("AGREEMENT_LINE_ID") REFERENCES "RENTAL_AGREEMENT_LINE" ("AGREEMENT_LINE_ID")
)
PRIMARY INDEX PI_VEHICLE_MAINTENANCE (VEHICLE_ID);