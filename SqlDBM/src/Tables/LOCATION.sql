-- ************************************** "LOCATION"
CREATE MULTISET TABLE "LOCATION" (
  "LOCATION_ID" integer NOT NULL,
  "REGION_ID" integer NOT NULL,
  "LOCATION_CODE" varchar(10) NOT NULL,
  "LOCATION_NAME" varchar(150) NOT NULL,
  "LOCATION_TYPE" varchar(20) NOT NULL,
  "ADDRESS_LINE1" varchar(150) NULL,
  "CITY" varchar(100) NULL,
  "STATE_PROVINCE" varchar(100) NULL,
  "POSTAL_CODE" varchar(20) NULL,
  "PHONE_NUMBER" varchar(20) NULL,
  "IS_ACTIVE" char(1) NULL DEFAULT 'Y',
  CONSTRAINT "PK_LOCATION" PRIMARY KEY ("LOCATION_ID"),
  CONSTRAINT "FK_LOCATION_REGION" FOREIGN KEY ("REGION_ID") REFERENCES "REGION" ("REGION_ID")
)
PRIMARY INDEX PI_LOCATION (LOCATION_ID);