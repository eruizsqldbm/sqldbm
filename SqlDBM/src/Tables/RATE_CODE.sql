-- ************************************** "RATE_CODE"
CREATE MULTISET TABLE "RATE_CODE" (
  "RATE_CODE_ID" integer NOT NULL,
  "RATE_PLAN_ID" integer NOT NULL,
  "VEHICLE_CLASS_ID" integer NOT NULL,
  "DAILY_RATE" decimal(10,2) NOT NULL,
  "WEEKLY_RATE" decimal(10,2) NULL,
  "MONTHLY_RATE" decimal(10,2) NULL,
  "MILEAGE_ALLOWANCE" integer NULL,
  "EXCESS_MILE_FEE" decimal(6,2) NULL,
  CONSTRAINT "PK_RATE_CODE" PRIMARY KEY ("RATE_CODE_ID"),
  CONSTRAINT "FK_RATECODE_PLAN" FOREIGN KEY ("RATE_PLAN_ID") REFERENCES "RATE_PLAN" ("RATE_PLAN_ID"),
  CONSTRAINT "FK_RATECODE_CLASS" FOREIGN KEY ("VEHICLE_CLASS_ID") REFERENCES "VEHICLE_CLASS" ("VEHICLE_CLASS_ID")
)
PRIMARY INDEX PI_RATE_CODE (RATE_CODE_ID);