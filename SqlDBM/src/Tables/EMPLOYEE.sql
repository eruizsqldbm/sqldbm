-- ************************************** "EMPLOYEE"
CREATE MULTISET TABLE "EMPLOYEE" (
  "EMPLOYEE_ID" integer NOT NULL,
  "ROLE_ID" integer NOT NULL,
  "LOCATION_ID" integer NOT NULL,
  "FIRST_NAME" varchar(50) NOT NULL,
  "LAST_NAME" varchar(50) NOT NULL,
  "EMAIL" varchar(150) NULL,
  "PHONE_NUMBER" varchar(20) NULL,
  "HIRE_DATE" date NULL,
  "TERMINATION_DATE" date NULL,
  "IS_ACTIVE" char(1) NULL DEFAULT 'Y',
  CONSTRAINT "PK_EMPLOYEE" PRIMARY KEY ("EMPLOYEE_ID"),
  CONSTRAINT "FK_EMPLOYEE_ROLE" FOREIGN KEY ("ROLE_ID") REFERENCES "EMPLOYEE_ROLE" ("ROLE_ID"),
  CONSTRAINT "FK_EMPLOYEE_LOCATION" FOREIGN KEY ("LOCATION_ID") REFERENCES "LOCATION" ("LOCATION_ID")
)
PRIMARY INDEX PI_EMPLOYEE (EMPLOYEE_ID);