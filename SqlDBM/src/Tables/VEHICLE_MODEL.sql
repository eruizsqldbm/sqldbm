-- ************************************** "VEHICLE_MODEL"
CREATE MULTISET TABLE "VEHICLE_MODEL" (
  "MODEL_ID" integer NOT NULL,
  "MAKE_ID" integer NOT NULL,
  "MODEL_NAME" varchar(50) NOT NULL,
  "MODEL_YEAR" smallint NOT NULL,
  "BODY_STYLE" varchar(30) NULL,
  "SEATING_CAPACITY" byteint NULL,
  CONSTRAINT "PK_VEHICLE_MODEL" PRIMARY KEY ("MODEL_ID"),
  CONSTRAINT "FK_MODEL_MAKE" FOREIGN KEY ("MAKE_ID") REFERENCES "VEHICLE_MAKE" ("MAKE_ID")
)
PRIMARY INDEX PI_VEHICLE_MODEL (MODEL_ID);