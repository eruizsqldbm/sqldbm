-- ************************************** "DRIVER_LICENSE"
CREATE MULTISET TABLE "DRIVER_LICENSE" (
  "DRIVER_LICENSE_ID" integer NOT NULL,
  "CUSTOMER_ID" integer NOT NULL,
  "LICENSE_NUMBER" varchar(30) NOT NULL,
  "ISSUING_STATE" varchar(50) NULL,
  "ISSUING_COUNTRY" varchar(50) NULL,
  "ISSUE_DATE" date NULL,
  "EXPIRATION_DATE" date NOT NULL,
  CONSTRAINT "PK_DRIVER_LICENSE" PRIMARY KEY ("DRIVER_LICENSE_ID"),
  CONSTRAINT "FK_LICENSE_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMER" ("CUSTOMER_ID")
)
PRIMARY INDEX PI_DRIVER_LICENSE (CUSTOMER_ID);