-- ************************************** "PAYMENT"
CREATE MULTISET TABLE "PAYMENT" (
  "PAYMENT_ID" integer NOT NULL,
  "RENTAL_AGREEMENT_ID" integer NOT NULL,
  "PAYMENT_METHOD_ID" integer NULL,
  "PAYMENT_TS" timestamp(0) NULL DEFAULT CURRENT_TIMESTAMP(0),
  "PAYMENT_AMOUNT" decimal(12,2) NOT NULL,
  "PAYMENT_TYPE" varchar(20) NULL DEFAULT 'CHARGE',
  "PAYMENT_STATUS" varchar(20) NULL DEFAULT 'COMPLETED',
  CONSTRAINT "PK_PAYMENT" PRIMARY KEY ("PAYMENT_ID"),
  CONSTRAINT "FK_PAYMENT_AGREEMENT" FOREIGN KEY ("RENTAL_AGREEMENT_ID") REFERENCES "RENTAL_AGREEMENT" ("RENTAL_AGREEMENT_ID"),
  CONSTRAINT "FK_PAYMENT_METHOD" FOREIGN KEY ("PAYMENT_METHOD_ID") REFERENCES "PAYMENT_METHOD" ("PAYMENT_METHOD_ID")
)
PRIMARY INDEX PI_PAYMENT (RENTAL_AGREEMENT_ID);