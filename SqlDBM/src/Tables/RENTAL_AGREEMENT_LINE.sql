CREATE MULTISET TABLE "RENTAL_AGREEMENT_LINE" (
  "AGREEMENT_LINE_ID" integer NOT NULL,
  "RENTAL_AGREEMENT_ID" integer NOT NULL,
  "LINE_TYPE" varchar(30) NOT NULL,
  "DESCRIPTION" varchar(200) NULL,
  "QUANTITY" decimal(8,2) NULL DEFAULT 1,
  "UNIT_PRICE" decimal(10,2) NOT NULL,
  "LINE_AMOUNT" decimal(12,2) NOT NULL,
  CONSTRAINT "PK_RA_LINE" PRIMARY KEY ("AGREEMENT_LINE_ID"),
  CONSTRAINT "FK_RALINE_AGREEMENT" FOREIGN KEY ("RENTAL_AGREEMENT_ID") REFERENCES "RENTAL_AGREEMENT" ("RENTAL_AGREEMENT_ID")
)
PRIMARY INDEX PI_RENTAL_AGREEMENT_LINE (RENTAL_AGREEMENT_ID);