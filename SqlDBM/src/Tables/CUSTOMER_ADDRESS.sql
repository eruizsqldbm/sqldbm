-- ************************************** "CUSTOMER_ADDRESS"
CREATE MULTISET TABLE "CUSTOMER_ADDRESS" (
  "ADDRESS_ID" integer NOT NULL,
  "CUSTOMER_ID" integer NOT NULL,
  "ADDRESS_TYPE" varchar(20) NULL DEFAULT 'HOME',
  "ADDRESS_LINE1" varchar(150) NOT NULL,
  "ADDRESS_LINE2" varchar(150) NULL,
  "CITY" varchar(100) NULL,
  "STATE_PROVINCE" varchar(100) NULL,
  "POSTAL_CODE" varchar(20) NULL,
  "COUNTRY_CODE" varchar(3) NULL,
  CONSTRAINT "PK_CUSTOMER_ADDRESS" PRIMARY KEY ("ADDRESS_ID"),
  CONSTRAINT "FK_ADDRESS_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMER" ("CUSTOMER_ID")
)
PRIMARY INDEX PI_CUSTOMER_ADDRESS (CUSTOMER_ID);