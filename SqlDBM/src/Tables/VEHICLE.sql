-- ************************************** "VEHICLE"
CREATE MULTISET TABLE "VEHICLE" (
  "VEHICLE_ID" integer NOT NULL,
  "MODEL_ID" integer NOT NULL,
  "VEHICLE_CLASS_ID" integer NOT NULL,
  "HOME_LOCATION_ID" integer NOT NULL,
  "VIN" varchar(17) NOT NULL,
  "LICENSE_PLATE" varchar(15) NOT NULL,
  "COLOR" varchar(30) NULL,
  "ODOMETER_MILES" integer NULL DEFAULT 0,
  "ACQUISITION_DATE" date NULL,
  "STATUS" varchar(20) NULL DEFAULT 'AVAILABLE',
  CONSTRAINT "PK_VEHICLE" PRIMARY KEY ("VEHICLE_ID"),
  CONSTRAINT "FK_VEHICLE_MODEL" FOREIGN KEY ("MODEL_ID") REFERENCES "VEHICLE_MODEL" ("MODEL_ID"),
  CONSTRAINT "FK_VEHICLE_CLASS" FOREIGN KEY ("VEHICLE_CLASS_ID") REFERENCES "VEHICLE_CLASS" ("VEHICLE_CLASS_ID"),
  CONSTRAINT "FK_VEHICLE_LOCATION" FOREIGN KEY ("HOME_LOCATION_ID") REFERENCES "LOCATION" ("LOCATION_ID")
)
PRIMARY INDEX PI_VEHICLE (VEHICLE_ID);