-- ************************************** "RENTAL_AGREEMENT"
CREATE MULTISET TABLE "RENTAL_AGREEMENT" (
  "RENTAL_AGREEMENT_ID" integer NOT NULL,
  "RESERVATION_ID" integer NULL,
  "CUSTOMER_ID" integer NOT NULL,
  "VEHICLE_ID" integer NOT NULL,
  "CHECKOUT_EMPLOYEE_ID" integer NOT NULL,
  "CHECKIN_EMPLOYEE_ID" integer NULL,
  "RATE_CODE_ID" integer NOT NULL,
  "PROTECTION_PLAN_ID" integer NULL,
  "PICKUP_LOCATION_ID" integer NOT NULL,
  "RETURN_LOCATION_ID" integer NULL,
  "CHECKOUT_TS" timestamp(0) NOT NULL,
  "SCHEDULED_RETURN_TS" timestamp(0) NOT NULL,
  "ACTUAL_RETURN_TS" timestamp(0) NULL,
  "ODOMETER_OUT" integer NULL,
  "ODOMETER_IN" integer NULL,
  "FUEL_LEVEL_OUT" varchar(10) NULL,
  "FUEL_LEVEL_IN" varchar(10) NULL,
  "AGREEMENT_STATUS" varchar(20) NULL DEFAULT 'OPEN',
  CONSTRAINT "PK_RENTAL_AGREEMENT" PRIMARY KEY ("RENTAL_AGREEMENT_ID"),
  CONSTRAINT "FK_RA_RESERVATION" FOREIGN KEY ("RESERVATION_ID") REFERENCES "RESERVATION" ("RESERVATION_ID"),
  CONSTRAINT "FK_RA_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMER" ("CUSTOMER_ID"),
  CONSTRAINT "FK_RA_VEHICLE" FOREIGN KEY ("VEHICLE_ID") REFERENCES "VEHICLE" ("VEHICLE_ID"),
  CONSTRAINT "FK_RA_CHECKOUT_EMP" FOREIGN KEY ("CHECKOUT_EMPLOYEE_ID") REFERENCES "EMPLOYEE" ("EMPLOYEE_ID"),
  CONSTRAINT "FK_RA_CHECKIN_EMP" FOREIGN KEY ("CHECKIN_EMPLOYEE_ID") REFERENCES "EMPLOYEE" ("EMPLOYEE_ID"),
  CONSTRAINT "FK_RA_RATECODE" FOREIGN KEY ("RATE_CODE_ID") REFERENCES "RATE_CODE" ("RATE_CODE_ID"),
  CONSTRAINT "FK_RA_PROTECTION" FOREIGN KEY ("PROTECTION_PLAN_ID") REFERENCES "PROTECTION_PLAN" ("PROTECTION_PLAN_ID"),
  CONSTRAINT "FK_RA_PICKUP_LOC" FOREIGN KEY ("PICKUP_LOCATION_ID") REFERENCES "LOCATION" ("LOCATION_ID"),
  CONSTRAINT "FK_RA_RETURN_LOC" FOREIGN KEY ("RETURN_LOCATION_ID") REFERENCES "LOCATION" ("LOCATION_ID")
)
PRIMARY INDEX PI_RENTAL_AGREEMENT (CUSTOMER_ID);